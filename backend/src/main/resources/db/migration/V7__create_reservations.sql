-- Migration V7 : Création des tables de réservation et des options

CREATE TABLE IF NOT EXISTS reservations (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR(30)    NOT NULL,
    user_id              BIGINT         NOT NULL,
    vehicle_id           BIGINT         NOT NULL,
    date_debut           DATE           NOT NULL,
    date_fin             DATE           NOT NULL,
    lieu_prise_en_charge VARCHAR(255)   NOT NULL,
    lieu_retour          VARCHAR(255)   NOT NULL,
    prix_total           NUMERIC(12, 2) NOT NULL,
    caution              NUMERIC(12, 2) NOT NULL,
    statut               VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_reservations_code UNIQUE (code),
    CONSTRAINT fk_reservations_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_reservations_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id) ON DELETE RESTRICT,
    CONSTRAINT chk_reservations_statut CHECK (statut IN ('PENDING', 'CONFIRMED', 'ACTIVE', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_reservations_dates CHECK (date_debut < date_fin),
    CONSTRAINT chk_reservations_prix_total CHECK (prix_total >= 0),
    CONSTRAINT chk_reservations_caution CHECK (caution >= 0)
);

CREATE TABLE IF NOT EXISTS reservation_options (
    reservation_id BIGINT      NOT NULL,
    option_name    VARCHAR(50) NOT NULL,
    CONSTRAINT pk_reservation_options PRIMARY KEY (reservation_id, option_name),
    CONSTRAINT fk_reservation_options_reservation FOREIGN KEY (reservation_id) REFERENCES reservations (id) ON DELETE CASCADE,
    CONSTRAINT chk_reservation_options_name CHECK (option_name IN ('GPS', 'BABY_SEAT', 'EXTRA_DRIVER'))
);

CREATE INDEX IF NOT EXISTS idx_reservations_user_id ON reservations (user_id);
CREATE INDEX IF NOT EXISTS idx_reservations_vehicle_id ON reservations (vehicle_id);
CREATE INDEX IF NOT EXISTS idx_reservations_statut ON reservations (statut);
CREATE INDEX IF NOT EXISTS idx_reservations_dates ON reservations (date_debut, date_fin);
