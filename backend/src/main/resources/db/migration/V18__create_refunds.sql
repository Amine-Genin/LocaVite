-- Migration V18 : Refonte de la table refunds pour la gestion des remboursements de paiements (total ou partiel)
-- (Notée initialement V15__create_refunds.sql dans les spécifications du backlog DGL, incrémentée à V18 suite aux migrations V13..V17)

CREATE SEQUENCE IF NOT EXISTS avoir_number_seq START WITH 1 INCREMENT BY 1;

DROP TABLE IF EXISTS refunds;

CREATE TABLE IF NOT EXISTS refunds (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id      BIGINT,
    reservation_id  BIGINT,
    montant         NUMERIC(12, 2) NOT NULL,
    raison          VARCHAR(255)   NOT NULL,
    statut          VARCHAR(30)    NOT NULL DEFAULT 'PENDING',
    methode         VARCHAR(30)    NOT NULL DEFAULT 'MANUAL',
    avoir_path      VARCHAR(512),
    reference       VARCHAR(100),
    audit_trail     TEXT,
    date_operation  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_refunds_payment FOREIGN KEY (payment_id)
        REFERENCES payments (id) ON DELETE CASCADE,
    CONSTRAINT fk_refunds_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservations (id) ON DELETE CASCADE,
    CONSTRAINT chk_refunds_montant CHECK (montant >= 0),
    CONSTRAINT chk_refunds_statut CHECK (statut IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED', 'MANUAL')),
    CONSTRAINT chk_refunds_methode CHECK (methode IN ('CMI', 'MANUAL', 'BANK_TRANSFER'))
);

CREATE INDEX IF NOT EXISTS idx_refunds_payment_id ON refunds (payment_id);
CREATE INDEX IF NOT EXISTS idx_refunds_reservation_id ON refunds (reservation_id);
CREATE INDEX IF NOT EXISTS idx_refunds_statut ON refunds (statut);
CREATE INDEX IF NOT EXISTS idx_refunds_date_operation ON refunds (date_operation DESC);
