ALTER TABLE reservation_contracts
    ADD COLUMN version INTEGER NOT NULL DEFAULT 1;

CREATE TABLE reservation_extensions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id      BIGINT         NOT NULL,
    ancienne_date_fin   DATE           NOT NULL,
    nouvelle_date_fin   DATE           NOT NULL,
    prix_supplementaire NUMERIC(12, 2) NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reservation_extension_reservation
        FOREIGN KEY (reservation_id) REFERENCES reservations (id) ON DELETE CASCADE,
    CONSTRAINT chk_reservation_extension_dates CHECK (ancienne_date_fin < nouvelle_date_fin),
    CONSTRAINT chk_reservation_extension_prix CHECK (prix_supplementaire >= 0)
);

CREATE INDEX idx_reservation_extensions_reservation_id
    ON reservation_extensions (reservation_id, created_at DESC);
