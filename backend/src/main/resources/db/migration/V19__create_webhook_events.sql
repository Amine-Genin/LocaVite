-- Migration V19 : Table webhook_events pour l'idempotence et la traçabilité
--                 des notifications serveur-à-serveur (Webhook CMI)
-- ============================================================================

CREATE TABLE IF NOT EXISTS webhook_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR(150) NOT NULL,
    source          VARCHAR(50)  NOT NULL DEFAULT 'CMI',
    payload         TEXT         NOT NULL,
    ip              VARCHAR(64)  NOT NULL,
    received_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at    TIMESTAMP WITH TIME ZONE,

    CONSTRAINT uq_webhook_events_event_id UNIQUE (event_id)
);

CREATE INDEX IF NOT EXISTS idx_webhook_events_event_id ON webhook_events(event_id);
CREATE INDEX IF NOT EXISTS idx_webhook_events_source_received ON webhook_events(source, received_at DESC);
CREATE INDEX IF NOT EXISTS idx_webhook_events_ip ON webhook_events(ip);
