CREATE TABLE seasons (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)   NOT NULL,
    date_debut  DATE           NOT NULL,
    date_fin    DATE           NOT NULL,
    coefficient NUMERIC(4, 2)  NOT NULL,
    CONSTRAINT chk_seasons_dates CHECK (date_debut < date_fin),
    CONSTRAINT chk_seasons_coefficient CHECK (coefficient > 0)
);

CREATE INDEX idx_seasons_dates ON seasons (date_debut, date_fin);

