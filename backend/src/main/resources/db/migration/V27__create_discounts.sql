CREATE TABLE IF NOT EXISTS discounts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(30)   NOT NULL,
    code        VARCHAR(60),
    libelle     VARCHAR(150)  NOT NULL,
    min_days    INTEGER,
    pourcentage NUMERIC(5, 2) NOT NULL,
    date_debut  DATE,
    date_fin    DATE,
    actif       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_discounts_code UNIQUE (code),
    CONSTRAINT chk_discounts_type CHECK (type IN ('LONG_DURATION', 'PROMO_CODE')),
    CONSTRAINT chk_discounts_pourcentage CHECK (pourcentage > 0 AND pourcentage <= 100),
    CONSTRAINT chk_discounts_min_days CHECK (min_days IS NULL OR min_days > 0),
    CONSTRAINT chk_discounts_dates CHECK (date_debut IS NULL OR date_fin IS NULL OR date_debut <= date_fin)
);

CREATE INDEX IF NOT EXISTS idx_discounts_type_actif ON discounts (type, actif);
