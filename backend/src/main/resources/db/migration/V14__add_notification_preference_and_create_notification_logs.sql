-- Migration V14 : Ajout de la préférence de notification et création de notification_logs

-- 1. Colonnes de préférence de notification et consentement opt-in dans users
ALTER TABLE users ADD COLUMN IF NOT EXISTS preference_notification VARCHAR(30) DEFAULT 'SMS';
ALTER TABLE users ADD COLUMN IF NOT EXISTS notification_opt_in BOOLEAN DEFAULT TRUE;

-- 2. Table notification_logs pour la traçabilité des envois SMS et WhatsApp
CREATE TABLE IF NOT EXISTS notification_logs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id    BIGINT,
    user_id           BIGINT,
    recipient         VARCHAR(100) NOT NULL,
    destinataire      VARCHAR(100),
    channel           VARCHAR(30)  NOT NULL,
    canal             VARCHAR(30),
    notification_type VARCHAR(50)  NOT NULL,
    type              VARCHAR(50),
    content           TEXT         NOT NULL,
    message           TEXT,
    status            VARCHAR(30)  NOT NULL,
    statut            VARCHAR(30),
    error_message     TEXT,
    attempts          INTEGER      NOT NULL DEFAULT 1,
    tentatives        INTEGER      NOT NULL DEFAULT 1,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notification_logs_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservations (id) ON DELETE SET NULL,
    CONSTRAINT fk_notification_logs_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_notification_logs_reservation_id ON notification_logs (reservation_id);
CREATE INDEX IF NOT EXISTS idx_notification_logs_user_id ON notification_logs (user_id);
CREATE INDEX IF NOT EXISTS idx_notification_logs_recipient ON notification_logs (recipient);
CREATE INDEX IF NOT EXISTS idx_notification_logs_channel ON notification_logs (channel);
CREATE INDEX IF NOT EXISTS idx_notification_logs_status ON notification_logs (status);
CREATE INDEX IF NOT EXISTS idx_notification_logs_created_at ON notification_logs (created_at DESC);
