CREATE TABLE refunds (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id  BIGINT         NOT NULL UNIQUE,
    montant         NUMERIC(12, 2) NOT NULL,
    raison          VARCHAR(255)   NOT NULL,
    statut          VARCHAR(20)    NOT NULL DEFAULT 'MANUAL',
    date_operation  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_refunds_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservations (id) ON DELETE CASCADE,
    CONSTRAINT chk_refunds_montant CHECK (montant >= 0),
    CONSTRAINT chk_refunds_statut CHECK (statut IN ('PENDING', 'MANUAL', 'COMPLETED'))
);

CREATE INDEX idx_refunds_reservation_id ON refunds (reservation_id);
