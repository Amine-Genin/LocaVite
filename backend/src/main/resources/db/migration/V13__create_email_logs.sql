-- Migration V13 : Création de la table email_logs pour la traçabilité des envois de courriels
-- (Notée initialement V11 dans les spécifications du backlog, incrémentée à V13 suite à l'antériorité de V11_extensions et V12_refunds)

CREATE TABLE IF NOT EXISTS email_logs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT,
    recipient      VARCHAR(255) NOT NULL,
    destinataire   VARCHAR(255),
    subject        VARCHAR(255) NOT NULL,
    sujet          VARCHAR(255),
    template_name  VARCHAR(100),
    status         VARCHAR(30)  NOT NULL,
    statut         VARCHAR(30),
    error_message  TEXT,
    attempts       INTEGER      NOT NULL DEFAULT 1,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_email_logs_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservations (id) ON DELETE SET NULL,
    CONSTRAINT chk_email_logs_status CHECK (status IN ('SENT', 'FAILED', 'PENDING', 'SUCCESS'))
);

CREATE INDEX IF NOT EXISTS idx_email_logs_reservation_id ON email_logs (reservation_id);
CREATE INDEX IF NOT EXISTS idx_email_logs_recipient ON email_logs (recipient);
CREATE INDEX IF NOT EXISTS idx_email_logs_status ON email_logs (status);
CREATE INDEX IF NOT EXISTS idx_email_logs_created_at ON email_logs (created_at DESC);
