ALTER TABLE reservations
    ADD COLUMN caution_statut VARCHAR(30) NOT NULL DEFAULT 'PENDING';

ALTER TABLE reservations
    ADD CONSTRAINT chk_reservations_caution_statut
        CHECK (caution_statut IN ('PENDING', 'HELD', 'RELEASED', 'PARTIALLY_RELEASED', 'CAPTURED'));

CREATE TABLE caution_transactions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT         NOT NULL,
    montant        NUMERIC(12, 2) NOT NULL,
    type           VARCHAR(20)    NOT NULL,
    statut         VARCHAR(30)    NOT NULL,
    date_operation TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    note           VARCHAR(500),
    CONSTRAINT fk_caution_transaction_reservation
        FOREIGN KEY (reservation_id) REFERENCES reservations (id) ON DELETE CASCADE,
    CONSTRAINT chk_caution_transaction_montant CHECK (montant > 0),
    CONSTRAINT chk_caution_transaction_type CHECK (type IN ('HOLD', 'RELEASE', 'CAPTURE')),
    CONSTRAINT chk_caution_transaction_statut
        CHECK (statut IN ('PENDING', 'HELD', 'RELEASED', 'PARTIALLY_RELEASED', 'CAPTURED'))
);

CREATE INDEX idx_caution_transactions_reservation_date
    ON caution_transactions (reservation_id, date_operation DESC);
