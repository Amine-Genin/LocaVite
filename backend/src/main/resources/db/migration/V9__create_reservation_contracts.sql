CREATE TABLE reservation_contracts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT       NOT NULL,
    language       VARCHAR(2)   NOT NULL,
    object_path    VARCHAR(512) NOT NULL,
    access_token   VARCHAR(64)  NOT NULL,
    generated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_contract_reservation_language UNIQUE (reservation_id, language),
    CONSTRAINT uk_contract_object_path UNIQUE (object_path),
    CONSTRAINT uk_contract_access_token UNIQUE (access_token),
    CONSTRAINT fk_contract_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservations (id) ON DELETE CASCADE,
    CONSTRAINT chk_contract_language CHECK (language IN ('FR', 'AR', 'EN'))
);
