-- Migration V17 : Création de la table invoices et de la séquence PostgreSQL invoice_number_seq
-- (Notée initialement V14 dans les spécifications du backlog DGL, incrémentée à V17 suite aux migrations V13..V16)

CREATE SEQUENCE IF NOT EXISTS invoice_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS invoices (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero        VARCHAR(30)    NOT NULL,
    payment_id    BIGINT         NOT NULL,
    montant_ht    NUMERIC(12, 2) NOT NULL,
    montant_tva   NUMERIC(12, 2) NOT NULL,
    montant_ttc   NUMERIC(12, 2) NOT NULL,
    chemin_pdf    VARCHAR(512)   NOT NULL,
    date_emission TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_invoices_numero UNIQUE (numero),
    CONSTRAINT uk_invoices_payment_id UNIQUE (payment_id),
    CONSTRAINT fk_invoices_payment FOREIGN KEY (payment_id)
        REFERENCES payments (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_invoices_payment_id ON invoices (payment_id);
CREATE INDEX IF NOT EXISTS idx_invoices_numero ON invoices (numero);
CREATE INDEX IF NOT EXISTS idx_invoices_date_emission ON invoices (date_emission DESC);
