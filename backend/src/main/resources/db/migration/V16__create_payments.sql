-- Migration V16 : Création de la table payments pour la traçabilité des transactions
-- (Notée initialement V13 dans les spécifications du backlog DGL, incrémentée à V16 suite à l'antériorité de V13_email_logs, V14_notification_logs et V15_enrich_seasons)

CREATE TABLE IF NOT EXISTS payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(30)    NOT NULL,
    reservation_id BIGINT         NOT NULL,
    user_id        BIGINT         NOT NULL,
    montant        NUMERIC(12, 2) NOT NULL,
    devise         VARCHAR(10)    NOT NULL DEFAULT 'MAD',
    methode        VARCHAR(30)    NOT NULL,
    statut         VARCHAR(30)    NOT NULL DEFAULT 'PENDING',
    reference      VARCHAR(100),
    transaction_id VARCHAR(100),
    metadata       TEXT,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_payments_code UNIQUE (code),
    CONSTRAINT fk_payments_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservations (id) ON DELETE CASCADE,
    CONSTRAINT fk_payments_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT chk_payments_montant CHECK (montant > 0),
    CONSTRAINT chk_payments_methode CHECK (methode IN ('CMI', 'CASH_DELIVERY', 'CASH_AGENCY', 'BANK_TRANSFER')),
    CONSTRAINT chk_payments_statut CHECK (statut IN ('PENDING', 'PROCESSING', 'SUCCESS', 'FAILED', 'REFUNDED', 'PARTIALLY_REFUNDED', 'CANCELLED'))
);

CREATE INDEX IF NOT EXISTS idx_payments_reservation_id ON payments (reservation_id);
CREATE INDEX IF NOT EXISTS idx_payments_user_id ON payments (user_id);
CREATE INDEX IF NOT EXISTS idx_payments_statut ON payments (statut);
CREATE INDEX IF NOT EXISTS idx_payments_code ON payments (code);
CREATE INDEX IF NOT EXISTS idx_payments_created_at ON payments (created_at DESC);
